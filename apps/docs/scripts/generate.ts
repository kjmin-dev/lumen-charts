// Packages use bundler-style extensionless relative imports (`./options`). Register a tiny resolve
// hook so Node can import constants directly from packages/*/src without a separate build step.
registerHooks({
	resolve(specifier, context, nextResolve) {
		if (
			(specifier.startsWith('./') || specifier.startsWith('../')) &&
			context.parentURL !== undefined &&
			context.parentURL.startsWith('file://') &&
			!/\.[a-z]+$/i.test(specifier)
		) {
			const base = fileURLToPath(new URL(specifier, context.parentURL));
			if (existsSync(`${base}.ts`)) {
				return { shortCircuit: true, url: pathToFileURL(`${base}.ts`).href };
			}
			if (existsSync(join(base, 'index.ts'))) {
				return { shortCircuit: true, url: pathToFileURL(join(base, 'index.ts')).href };
			}
		}
		return nextResolve(specifier, context);
	},
});

