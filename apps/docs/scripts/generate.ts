function rewriteGuideLinks(markdown: string): string {
	return (
		markdown
			// Links between sibling guides: `(drawings.md)` or `(heatmap-scatter.md#indicators-over-marks)`
			.replace(/\]\(([a-z0-9-]+)\.md(#[^)]+)?\)/g, (_, slug: string, hash: string | undefined) => {
				return `](/guides/${slug}/${hash ?? ''})`;
			})
			// Links to design docs or benchmark docs outside docs/guide/
			.replace(/\]\(\.\.\/([^)]+)\)/g, (_, target: string) => `](${REPO}/docs/${target})`)
	);
}

function tabPanel(label: string, lang: string, code: string): string {
	return `<TabItem label=${JSON.stringify(label)}>\n\n\`\`\`${lang}\n${code.trim()}\n\`\`\`\n\n</TabItem>`;
}

function formatCodeTabs(vanillaLang: string, vanillaBody: string, tabs: GuideCodeTabs): string {
	return [
		'<Tabs syncKey="framework">',
		tabPanel('Vanilla', vanillaLang || 'ts', vanillaBody),
		tabPanel('React', 'tsx', tabs.react),
		tabPanel('Vue 3', 'vue', tabs.vue),
		tabPanel('Svelte 5', 'svelte', tabs.svelte),
		tabPanel('Solid', 'tsx', tabs.solid),
		'</Tabs>',
	].join('\n');
}

function applyGuideExamples(
	slug: string,
	markdown: string,
	examples: readonly GuideCodeTabs[] | undefined,
): { body: string; hasTabs: boolean } {
	if (examples === undefined || examples.length === 0) {
		return { body: markdown, hasTabs: false };
	}

	const byIndex = new Map<number, GuideCodeTabs>();
	for (const entry of examples) {
		if (byIndex.has(entry.blockIndex)) {
			throw new Error(`guide-examples.ts has duplicate blockIndex ${entry.blockIndex} for ${slug}`);
		}
		byIndex.set(entry.blockIndex, entry);
	}

	let currentIndex = 0;
	const matched = new Set<number>();
	const body = markdown.replace(/^```([a-z0-9_-]*)\n([\s\S]*?)\n```$/gm, (full, lang: string, code: string) => {
		const index = currentIndex++;
		const entry = byIndex.get(index);
		if (entry === undefined) {
			return full;
		}
		if (!code.includes(entry.match)) {
			throw new Error(
				`guide-examples.ts drift in docs/guide/${slug}.md block #${index}: expected substring ${JSON.stringify(entry.match)}`,
			);
		}
		matched.add(index);
		return formatCodeTabs(lang, code, entry);
	});

	for (const entry of examples) {
		if (!matched.has(entry.blockIndex)) {
			throw new Error(
				`guide-examples.ts references block #${entry.blockIndex} in docs/guide/${slug}.md, which only has ${currentIndex} fenced block(s)`,
			);
		}
	}

	return { body, hasTabs: true };
}

async function generateGuides(): Promise<void> {
	const guideDir = join(root, 'docs/guide');
	const files = (await readdir(guideDir)).filter(file => file.endsWith('.md')).toSorted();
	const planned = new Set(GUIDES.map(entry => `${entry.slug}.md`));
	const missed = files.filter(file => !planned.has(file));
	if (missed.length > 0) {
		throw new Error(`docs/guide has unmapped guide file(s): ${missed.join(', ')}`);
	}
	const validSlugs = new Set(GUIDES.map(entry => entry.slug));
	for (const slug of Object.keys(GUIDE_EXAMPLES)) {
		if (!validSlugs.has(slug)) {
			throw new Error(`guide-examples.ts references unknown guide slug: ${slug}`);
		}
	}

	await Promise.all(
		GUIDES.map(async (entry, index) => {
			const sourceRel = `docs/guide/${entry.slug}.md`;
			const raw = await readFile(join(root, sourceRel), 'utf8');
			const headingMatch = raw.match(/^# (.+)\n/);
			if (headingMatch === null) {
				throw new Error(`${sourceRel} is missing a leading "# Title" heading`);
			}
			const title = headingMatch[1]!.trim();
			const rewritten = rewriteGuideLinks(raw.slice(headingMatch[0].length).trim());
			const { body: bodyWithoutH1, hasTabs } = applyGuideExamples(entry.slug, rewritten, GUIDE_EXAMPLES[entry.slug]);
			const isMdx = entry.demo !== undefined || hasTabs;

			const parts: string[] = [
				isMdx ? NOTE(sourceRel) : `<!-- Generated by apps/docs/scripts/generate.ts from ${sourceRel}. Do not edit. -->`,
			];
			const imports: string[] = [];
			if (hasTabs) {
				imports.push("import { Tabs, TabItem } from '@astrojs/starlight/components';");
			}
			if (entry.demo !== undefined) {
				imports.push("import ChartDemo from '../../../components/ChartDemo.astro';");
			}
			if (imports.length > 0) {
				parts.push(imports.join('\n'));
			}
			if (entry.demo !== undefined) {
				const heightAttr = entry.demo.height === undefined ? '' : ` height={${entry.demo.height}}`;
				parts.push(
					`<ChartDemo name=${JSON.stringify(entry.demo.name)} title=${JSON.stringify(entry.demo.title)}${heightAttr} />`,
				);
				parts.push(`<p class="demo-caption">${entry.demo.caption}</p>`);
			}
			parts.push(bodyWithoutH1);

			const ext = isMdx ? 'mdx' : 'md';
			await writePage(
				`guides/${entry.slug}.${ext}`,
				{ title, description: entry.description, order: index + 1 },
				parts.join('\n\n'),
			);
		}),
	);
}

