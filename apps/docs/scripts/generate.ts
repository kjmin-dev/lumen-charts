const swatch = (color: string) => `<span class="swatch" style="background:${color}"></span>\`${color}\``;

function fmt(value: unknown): string {
	if (value === Infinity) {
		return '`Infinity`';
	}
	if (typeof value === 'string') {
		return value === '' ? '`""`' : `\`${JSON.stringify(value)}\``;
	}
	return `\`${JSON.stringify(value)}\``;
}

function seriesOptionTable(defaults: Record<string, unknown>): string {
	return table(
		['Option', 'Default'],
		Object.entries(defaults).map(([key, value]) => [
			`\`${key}\``,
			typeof value === 'string' && /^#|^rgba?\(/.test(value) ? swatch(value) : fmt(value),
		]),
	);
}

