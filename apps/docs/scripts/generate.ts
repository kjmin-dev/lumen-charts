interface Frontmatter {
	title: string;
	description: string;
	order?: number;
}

async function writePage(path: string, frontmatter: Frontmatter, body: string): Promise<void> {
	const file = join(content, path);
	await mkdir(join(file, '..'), { recursive: true });
	const lines = [
		`title: ${JSON.stringify(frontmatter.title)}`,
		`description: ${JSON.stringify(frontmatter.description)}`,
	];
	if (frontmatter.order !== undefined) {
		lines.push('sidebar:');
		lines.push(`  order: ${frontmatter.order}`);
	}
	await writeFile(file, `---\n${lines.join('\n')}\n---\n\n${body.trim()}\n`);
}

const escapeCell = (text: string) => text.replaceAll('|', '\\|');

function table(header: string[], rows: string[][]): string {
	return [
		`| ${header.join(' | ')} |`,
		`| ${header.map(() => '---').join(' | ')} |`,
		...rows.map(row => `| ${row.map(escapeCell).join(' | ')} |`),
	].join('\n');
}

